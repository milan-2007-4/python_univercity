t = (10, 20, 30, 40, 50)

print("Tuple =", t)

print("Length =", len(t))
print("Count of 20 =", t.count(20))
print("Index of 30 =", t.index(30))
print("Minimum =", min(t))
print("Maximum =", max(t))
print("Sorted =", sorted(t))
print("Reversed =", tuple(reversed(t)))
print("Comparison =", (1, 2, 3) > (1, 2, 1))