# Program 9

print("Break Statement")

for i in range(1,11):
    if i == 6:
        break
    print(i)

print("\nContinue Statement")

for i in range(1,11):
    if i == 6:
        continue
    print(i)

print("\nPass Statement")

for i in range(1,6):
    if i == 3:
        pass
    print(i)